const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const cheerio = require('cheerio');
const root = path.resolve(__dirname, '..');
const origin = 'https://assets.invalid/';
const media = /\.(?:png|jpe?g|svg|webp|gif|avif|ico|ttf|woff2?)$/i;

function revision(bytes, file) {
  const content = /\.(?:js|css|svg)$/i.test(file) ? bytes.toString('utf8').replace(/\r\n/g, '\n') : bytes;
  return crypto.createHash('sha256').update(content).digest('hex').slice(0, 16);
}

function versionedUrl(value, versions) {
  if (/^(?:[a-z][a-z\d+.-]*:|\/\/|#)/i.test(value)) return value;
  const url = new URL(value, 'https://assets.invalid/');
  const hash = versions[url.pathname.slice(1)];
  if (!hash) return value;
  url.searchParams.set('r', hash);
  return value.split(/[?#]/, 1)[0] + url.search + url.hash;
}

function generatedResolver(versions) {
  return '// Generated by tools/sync-web-assets.cjs. Do not edit.\n(() => {\n' +
    `  const versions = ${JSON.stringify(versions, null, 2)};\n` +
    `  const resolve = ${versionedUrl.toString().replace(/\r\n/g, '\n')};\n` +
    '  window.WTAssets = Object.freeze({ url: value => resolve(value, versions) });\n})();\n';
}

function rewriteCss(source, file, versions) {
  return source.replace(/url\(\s*(?:"([^"\n]*)"|'([^'\n]*)'|([^\s)'"\n]+))\s*\)/gi, (match, double, single, bare) => {
    const value = double ?? single ?? bare;
    if (/^(?:[a-z][a-z\d+.-]*:|\/\/|#)/i.test(value)) return match;
    const url = new URL(value, new URL(file, origin));
    assert(versions[url.pathname.slice(1)], `Unversioned CSS dependency: ${file}: ${value}`);
    const updated = versionedUrl(value, { [new URL(value, origin).pathname.slice(1)]: versions[url.pathname.slice(1)] });
    return match.replace(value, updated);
  });
}

function rewriteHtml(source, contents) {
  const $ = cheerio.load(source, { sourceCodeLocationInfo: true });
  const edits = [];
  for (const node of $('script[src], link[rel="stylesheet"][href], link[rel="icon"][href], img[src]').toArray()) {
    const attribute = node.name === 'link' ? 'href' : 'src';
    const value = $(node).attr(attribute);
    if (/^(?:[a-z][a-z\d+.-]*:|\/\/|#)/i.test(value)) continue;
    const file = new URL(value, origin).pathname.slice(1);
    assert(contents.has(file), `Missing HTML asset: ${file}`);
    const updated = versionedUrl(value, { [file]: revision(contents.get(file), file) });
    if (updated === value) continue;
    const location = node.sourceCodeLocation?.attrs?.[attribute];
    assert(location, `Missing source location for ${file}`);
    edits.push({ ...location, text: `${attribute}="${updated.replaceAll('&', '&amp;').replaceAll('"', '&quot;')}"` });
  }
  for (const edit of edits.sort((a, b) => b.startOffset - a.startOffset)) {
    source = source.slice(0, edit.startOffset) + edit.text + source.slice(edit.endOffset);
  }
  return source;
}

function buildFolder(directory) {
  const contents = new Map();
  function walk(relative) {
    const absolute = path.join(directory, relative);
    if (!fs.existsSync(absolute)) return;
    for (const entry of fs.readdirSync(absolute, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
      const file = relative ? `${relative}/${entry.name}` : entry.name;
      assert(!entry.isSymbolicLink(), `Asset symlinks are not supported: ${file}`);
      if (entry.isDirectory()) walk(file);
      else if (media.test(file) || /\.(?:js|css|html)$/i.test(file)) contents.set(file, fs.readFileSync(path.join(directory, file)));
    }
  }
  walk('');
  const versions = Object.fromEntries([...contents].filter(([file]) => media.test(file)).map(([file, bytes]) => [file, revision(bytes, file)]));
  contents.set('asset-urls.js', Buffer.from(generatedResolver(versions)));
  for (const [file, bytes] of contents) {
    if (file.endsWith('.css')) contents.set(file, Buffer.from(rewriteCss(bytes.toString('utf8'), file, versions)));
  }
  contents.set('index.html', Buffer.from(rewriteHtml(contents.get('index.html').toString('utf8'), contents)));
  return { contents, mediaCount: Object.keys(versions).length };
}

function syncWebAssets(base = root, { check = false } = {}) {
  const pending = [];
  const counts = {};
  for (const folder of ['public', 'docs']) {
    const directory = path.join(base, folder);
    const { contents, mediaCount } = buildFolder(directory);
    counts[folder] = { assets: contents.size, media: mediaCount };
    for (const [file, bytes] of contents) {
      const absolute = path.join(directory, file);
      const existing = fs.existsSync(absolute) ? fs.readFileSync(absolute) : null;
      const equal = existing && (/\.(?:js|css|html)$/i.test(file)
        ? existing.toString('utf8').replace(/\r\n/g, '\n') === bytes.toString('utf8').replace(/\r\n/g, '\n')
        : existing.equals(bytes));
      if (!equal) pending.push({ file: `${folder}/${file}`, absolute, bytes });
    }
  }
  if (check) assert.equal(pending.length, 0, `Stale asset URLs. Run npm run sync:web-assets:\n${pending.map(item => item.file).join('\n')}`);
  else for (const item of pending) fs.writeFileSync(item.absolute, item.bytes);
  return { changed: pending.map(item => item.file), counts };
}

if (require.main === module) {
  try { console.log(JSON.stringify(syncWebAssets(root, { check: process.argv.includes('--check') }), null, 2)); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
module.exports = { revision, versionedUrl, generatedResolver, rewriteCss, rewriteHtml, buildFolder, syncWebAssets };
